import { render } from "@react-email/render";
import { createElement } from "react";

import type { EmailLocale } from "./locale";
import AuthEmail, { authCopy, type AuthEmailKind } from "./templates/auth";

/** Every message Supabase Auth sends for the app, in the order docs/DEPLOY.md lists them. */
export const AUTH_EMAIL_KINDS: AuthEmailKind[] = ["confirmation", "recovery", "email_change"];

/** The name each one has in the dashboard (Authentication, Emails, Templates). */
const DASHBOARD_NAME: Record<AuthEmailKind, string> = {
  confirmation: "Confirm signup",
  recovery: "Reset password",
  email_change: "Change email address",
};

/**
 * True when the account's metadata says English: the `locale` the sign-up
 * writes. `printf` first, because an account without it has no value there and
 * `eq` cannot compare that with a string; such an account reads Portuguese.
 */
const IF_ENGLISH = '{{ if eq (printf "%v" .Data.locale) "en" }}';

/**
 * The subject in the reader's language. Supabase runs the subject through the
 * same template engine and fields as the body, so one line holds both.
 */
export function supabaseSubject(kind: AuthEmailKind): string {
  return `${IF_ENGLISH}${authCopy("en", kind).subject}{{ else }}${authCopy("pt-BR", kind).subject}{{ end }}`;
}

const rendered = (locale: EmailLocale, kind: AuthEmailKind) =>
  render(createElement(AuthEmail, { locale, kind }), { pretty: true });

/**
 * One file of supabase/templates/: the message rendered in each language from
 * the same shell as every other e-mail, the English one behind the account's
 * locale. Supabase strips the note at the top (a template comment) and every
 * HTML comment before sending.
 */
export async function supabaseTemplate(kind: AuthEmailKind): Promise<string> {
  const [en, pt] = await Promise.all([rendered("en", kind), rendered("pt-BR", kind)]);
  const note = [
    "{{- /*",
    `  ${DASHBOARD_NAME[kind]}, sent by Supabase Auth. GENERATED: do not edit this file.`,
    "  The source is packages/email (templates/auth.tsx, the copy in copy/pt-BR.ts",
    "  and copy/en.ts, the frame in templates/shell.tsx); after changing it, run",
    "  npm run supabase:templates -w @flyee/email. Local development reads this file",
    "  through supabase/config.toml; the hosted project gets it pasted in",
    "  Authentication, Emails, Templates, with the subject the same command checks",
    "  in config.toml (docs/DEPLOY.md).",
    "*/ -}}",
  ].join("\n");
  // The dashes trim the line breaks around each branch, so a message starts at its doctype.
  const branches = [IF_ENGLISH.replace("}}", "-}}"), en.trim(), "{{- else -}}", pt.trim(), "{{- end }}"];
  return `${[note, ...branches].join("\n")}\n`;
}
